# PTAD v2.5 WRAPPER CLASS
# ============================================================

class PTADv25:
    """
    PTAD v2.5 — Option B Complete Fix
    ==============================================
    Wraps PTAD v2.4 with three targeted fixes:

    Fix 1: Pressure Micro-Detector
           Lightweight LR on TP2/TP3/DV_pressure
           Catches F2 (pipe burst) early warnings
           Ensembled: score = α·base + (1-α)·pressure

    Fix 2: Cold Start Suppression (Rule-based)
           oil<45°C + motor>3.5A → dampen by 0.72
           Eliminates winter morning false alarms

    Fix 3: Boundary Temp Fix (Rule-based)
           oil 71–74°C → require compound evidence
           (duty>0.93 AND motor>5.5) else dampen
    """
    VERSION = '2.5'

    def __init__(self, base_model, pressure_pipeline,
                 p_features, alpha, pp_config):
        self.base               = base_model
        self.pressure_pipeline  = pressure_pipeline
        self.p_features         = p_features
        self.alpha              = float(alpha)
        self.pp_config          = pp_config
        # Expose fusion.threshold so downstream code works unchanged
        self.fusion             = type('Fusion', (), {
            'threshold': base_model.fusion.threshold
        })()

    # ── Internal helpers ──────────────────────────────────

    def _pressure_score_df(self, df):
        X = df[self.p_features].fillna(0).values
        return self.pressure_pipeline.predict_proba(X)[:, 1]

    def _pressure_score_dict(self, features):
        row = {f: features.get(f, 0) for f in self.p_features}
        X   = np.array([list(row.values())])
        return float(self.pressure_pipeline.predict_proba(X)[0, 1])

    def _level(self, score):
        t = self.fusion.threshold
        if   score >= t * 1.25: return 'CRITICAL'
        elif score >= t:         return 'WARNING'
        else:                    return 'NORMAL'

    def _apply_single_pp(self, score, oil_temp, motor, duty):
        """Apply Fix 2 + 3 to a single score."""
        t   = self.fusion.threshold
        cfg = self.pp_config
        fix = None

        # Fix 2: Cold start
        if (oil_temp < cfg['cold_oil_max'] and
                motor > cfg['cold_motor_min'] and
                score >= t):
            score *= cfg['cold_dampen']
            fix    = 'COLD_START_SUPPRESSED'

        # Fix 3: Boundary temp (only if not already fixed by cold)
        elif (cfg['btemp_low'] <= oil_temp <= cfg['btemp_high']
                and score >= t):
            compound = (duty > cfg['compound_duty_min'] and
                        motor > cfg['compound_motor_min'])
            if not compound:
                score *= cfg['btemp_dampen']
                fix    = 'BOUNDARY_TEMP_DAMPENED'

        return float(np.clip(score, 0, 1)), fix

    # ── Public API (same interface as v2.4) ───────────────

    def predict_single(self, features, timestamp=None):
        # Base prediction
        base_out = self.base.predict_single(features, timestamp)

        # Pressure micro score
        p_score = self._pressure_score_dict(features)

        # Ensemble
        raw_score = (self.alpha * base_out.railsense_score
                     + (1 - self.alpha) * p_score)

        # Post-processing
        oil   = features.get('Oil_temperature', 60)
        motor = features.get('Motor_current',    0)
        duty  = features.get('duty_cycle_5min',  0)
        final_score, fix_note = self._apply_single_pp(raw_score, oil, motor, duty)

        # Update output object (same PTADOutput dataclass)
        base_out.railsense_score = final_score
        base_out.alert_level     = self._level(final_score)
        base_out.score_components.update({
            'pressure_micro' : float(p_score),
            'ensemble_alpha' : self.alpha,
            'fix_note'       : fix_note or 'none',
        })

        return base_out

    def predict_batch(self, df):
        # Base scores
        base_scores, _, base_outputs = self.base.predict_batch(df)

        # Pressure micro scores
        p_scores = self._pressure_score_df(df)

        # Ensemble
        raw_scores = self.alpha * base_scores + (1 - self.alpha) * p_scores

        # Post-processing (vectorized)
        final_scores, cold_n, bound_n = postprocess_scores(
            raw_scores, df, self.fusion.threshold, self.pp_config
        )

        levels = [self._level(s) for s in final_scores]

        # Patch outputs
        for i, out in enumerate(base_outputs):
            out.railsense_score = float(final_scores[i])
            out.alert_level     = levels[i]
            out.score_components['pressure_micro'] = float(p_scores[i])

        return final_scores, levels, base_outputs


