class TemporalEngine:
    TEMPORAL_COLS=[
        'T1_motor_overload_duration','T2_oil_temp_slope_30min',
        'T3_lps_trend_1hr','T4_pressure_instability_accel',
        'T5_efficiency_trend_1hr','T6_divergence_accel',
    ]
    def __init__(self):
        self.baselines={}; self.fitted=False
        self.abs_thresholds={
            'T1_motor_overload_duration':{'warn':600,'crit':1800},
            'T2_oil_temp_slope_30min':{'warn':0.05,'crit':0.20},
            'T3_lps_trend_1hr':{'warn':0.01,'crit':0.05},
            'T4_pressure_instability_accel':{'warn':0.001,'crit':0.005},
            'T5_efficiency_trend_1hr':{'warn':-1.0,'crit':-3.0},
            'T6_divergence_accel':{'warn':0.001,'crit':0.005},
        }

    def compute(self,df,gap_col='gap_flag'):
        df=df.copy().sort_values('timestamp').reset_index(drop=True)
        df['_seg']=df[gap_col].cumsum() if gap_col in df.columns else 0

        def safe_slope(x):
            if len(x)<10: return 0.0
            try: return float(np.polyfit(np.arange(len(x)),x,1)[0])
            except: return 0.0

        # Skip temporal computation for synthetic rows
        real_mask = df.get('is_synthetic', pd.Series(0, index=df.index)) == 0

        df['_mh']=(df['Motor_current']>5.5).astype(float)
        grp=(df['_mh']!=df['_mh'].shift()).cumsum()
        df['T1_motor_overload_duration']=(
            df.groupby(grp)['_mh'].transform('cumsum')*df['_mh']
        ).astype('float32')

        for col,src,w,mp in [
            ('T2_oil_temp_slope_30min','Oil_temperature',1800,60),
            ('T3_lps_trend_1hr','LPS_freq_10min',3600,300),
            ('T5_efficiency_trend_1hr','compressor_efficiency',3600,300),
            ('T6_divergence_accel','sensor_divergence',1800,300),
        ]:
            df[col]=(
                df.groupby('_seg')[src]
                .transform(lambda x:x.rolling(w,min_periods=mp)
                           .apply(safe_slope,raw=True))
            ).fillna(0).astype('float32')

        df['_pv']=(
            df.groupby('_seg')['pressure_variance_10min']
            .transform(lambda x:x.rolling(600,min_periods=60).mean())
        ).fillna(0)
        df['T4_pressure_instability_accel']=(
            df.groupby('_seg')['_pv']
            .transform(lambda x:x.rolling(1800,min_periods=300)
                       .apply(safe_slope,raw=True))
        ).fillna(0).astype('float32')

        df.drop(columns=['_mh','_pv','_seg'],inplace=True,errors='ignore')
        return df

    def fit_baselines(self,normal_df):
        for col in self.TEMPORAL_COLS:
            if col not in normal_df.columns:
                self.baselines[col]={'median':0,'mad':1}; continue
            v=normal_df[col].dropna().values
            self.baselines[col]={
                'median':float(np.median(v)),
                'mad':float(median_abs_deviation(v)+1e-6),
            }
        self.fitted=True

    def score_row(self,features):
        scores={}
        weights={
            'T1_motor_overload_duration':0.35,
            'T2_oil_temp_slope_30min':0.25,
            'T3_lps_trend_1hr':0.15,
            'T4_pressure_instability_accel':0.10,
            'T5_efficiency_trend_1hr':0.10,
            'T6_divergence_accel':0.05,
        }
        for col in self.TEMPORAL_COLS:
            val=features.get(col,0)
            if col not in self.abs_thresholds:
                scores[col]=0.0; continue
            t=self.abs_thresholds[col]
            warn,crit=t['warn'],t['crit']
            if col=='T5_efficiency_trend_1hr':
                val_abs=abs(min(val,0))
                warn_abs,crit_abs=abs(warn),abs(crit)
                if val_abs<=warn_abs: s=0.0
                elif val_abs>=crit_abs: s=1.0
                else:
                    t_=(val_abs-warn_abs)/(crit_abs-warn_abs+1e-10)
                    s=float(3*t_**2-2*t_**3)
            elif col in ['T2_oil_temp_slope_30min','T3_lps_trend_1hr',
                         'T4_pressure_instability_accel','T6_divergence_accel']:
                val_pos=max(val,0)
                if val_pos<=warn: s=0.0
                elif val_pos>=crit: s=1.0
                else:
                    t_=(val_pos-warn)/(crit-warn+1e-10)
                    s=float(3*t_**2-2*t_**3)
            else:
                if val<=warn: s=0.0
                elif val>=crit: s=1.0
                else:
                    t_=(val-warn)/(crit-warn+1e-10)
                    s=float(3*t_**2-2*t_**3)
            scores[col]=float(np.clip(s,0,1))
        agg=sum(scores.get(c,0)*w for c,w in weights.items())
        scores['temporal_aggregate']=float(np.clip(agg,0,1))
        return scores

