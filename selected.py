# If failure_id available → use only F2 rows as positives
# Otherwise → use all label>0 as positives (still helps F2)

def build_pressure_training(df, balance_ratio=8):
    """Build balanced train set. F2-focused if failure_id present."""
    y = (df['label'] > 0).astype(int).values
    X = df[P_FEATURES].fillna(0).values

    if 'failure_id' in df.columns:
        # Boost F2 cases by oversampling them 3x
        f2_mask  = (df['failure_id'] == 2) & (df['label'] > 0)
        nf2_mask = (df['failure_id'] != 2) & (df['label'] > 0)
        norm_mask = df['label'] == 0

        f2_X  = X[f2_mask.values]
        nf2_X = X[nf2_mask.values]
        norm_X = X[norm_mask.values]

        f2_y   = np.ones(len(f2_X))
        nf2_y  = np.ones(len(nf2_X))
        norm_y = np.zeros(len(norm_X))

        # Sample normal rows to balance
        n_pos = len(f2_X) * 3 + len(nf2_X)
        n_sample = min(n_pos * balance_ratio, len(norm_X))
        idx = np.random.RandomState(42).choice(len(norm_X), n_sample, replace=False)

        X_out = np.vstack([
            f2_X, f2_X, f2_X,   # oversample F2 3x
            nf2_X,
            norm_X[idx]
        ])
        y_out = np.concatenate([f2_y, f2_y, f2_y, nf2_y, norm_y[idx]])
        print(f"  F2 rows (3x): {len(f2_X)*3:,} | Other fail: {len(nf2_X):,} | Normal: {len(idx):,}")
    else:
        # No failure_id → standard balanced sampling
        n_fail = y.sum()
        n_sample = min(n_fail * balance_ratio, (y==0).sum())
        norm_idx = np.where(y==0)[0]
        chosen   = np.random.RandomState(42).choice(norm_idx, n_sample, replace=False)
        sel = np.concatenate([np.where(y==1)[0], chosen])
        X_out, y_out = X[sel], y[sel]
        print(f"  Failures: {y_out.sum():,} | Normal: {(y_out==0).sum():,}")

    return X_out, y_out

