class PTADv2:
    VERSION='2.4'

    def __init__(self):
        self.physics=PhysicsEngine(); self.temporal=TemporalEngine()
        self.statistical=StatisticalEngine(); self.fusion=FusionLayer()
        self.alert=AlertEngine(); self.fitted=False

    def fit(self,train_smote,train_orig,val_df,feature_cols,label_col='label'):
        print(f"\n{'='*60}")
        print(f"PTAD v{self.VERSION} TRAINING")
        print(f"{'='*60}")
        self.feature_cols=feature_cols

        print("\n[1/4] Temporal features...")
        train_smote=self.temporal.compute(train_smote)
        train_orig =self.temporal.compute(train_orig)
        val_df     =self.temporal.compute(val_df)
        all_features=feature_cols+[c for c in self.temporal.TEMPORAL_COLS
                                    if c in train_smote.columns]

        print("[2/4] Statistical baseline (REAL normal rows only)...")
        # CRITICAL: fit on ORIGINAL normal data, not synthetic
        normal_real=train_orig[train_orig[label_col]==0]
        self.temporal.fit_baselines(normal_real)
        self.statistical.fit(normal_real,all_features)

        print("[3/4] Scoring rows...")
        def score_df(df,name):
            ps,ts,ss=[],[],[]
            for i,(_,row) in enumerate(df.iterrows()):
                rd=row.to_dict()
                ps.append(self.physics.aggregate(self.physics.evaluate(rd)))
                ts.append(self.temporal.score_row(rd).get('temporal_aggregate',0.0))
                ss.append(self.statistical.score_row(rd).get('statistical_aggregate',0.0))
                if i%5000==0: print(f"  {name}:{i:>6,}/{len(df):,}",end='\r')
            return np.array(ps),np.array(ts),np.array(ss)

        p_smote,t_smote,s_smote=score_df(train_smote,'SMOTE train')
        p_vl,t_vl,s_vl         =score_df(val_df,     'Val        ')

        l_smote=(train_smote[label_col]>0).astype(int).values
        l_vl   =(val_df[label_col]>0).astype(int).values

        print("\n[4/4] Fusion optimization (SMOTE train, validated on real val)...")
        self.fusion.fit(p_smote,t_smote,s_smote,l_smote,
                        p_vl,t_vl,s_vl,l_vl)

        self.fitted=True
        self.all_features=all_features
        print(f"\nPTAD v{self.VERSION} training complete.")
        return self

    def predict_single(self,features,timestamp=None):
        p_sigs=self.physics.evaluate(features)
        p_agg =self.physics.aggregate(p_sigs)
        t_agg =self.temporal.score_row(features).get('temporal_aggregate',0.0)
        s_agg =self.statistical.score_row(features).get('statistical_aggregate',0.0)
        score,level,conf=self.fusion.fuse(p_agg,t_agg,s_agg)
        top3=sorted(p_sigs,key=lambda x:x.score,reverse=True)[:3]
        dom=top3[0].failure_mode if top3[0].score>0.1 else ''
        return PTADOutput(
            timestamp=timestamp,railsense_score=score,
            alert_level=level,confidence=conf,
            physics_score=p_agg,temporal_score=t_agg,
            statistical_score=s_agg,top_physics_signals=top3,
            dominant_failure_mode=dom,
            recommended_action=self.alert.recommended_action(level,dom),
            fusion_weights=self.fusion.weights,
            score_components={
                'physics':self.fusion.weights['physics']*p_agg,
                'temporal':self.fusion.weights['temporal']*t_agg,
                'statistical':self.fusion.weights['statistical']*s_agg,
            }
        )

    def predict_batch(self,df):
        df=self.temporal.compute(df)
        scores,levels,outputs=[],[],[]
        for _,row in df.iterrows():
            rd=row.to_dict()
            out=self.predict_single(rd,str(row.get('timestamp','')))
            scores.append(out.railsense_score)
            levels.append(out.alert_level)
            outputs.append(out)
        return np.array(scores),levels,outputs

