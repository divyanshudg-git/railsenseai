class StatisticalEngine:
    def __init__(self):
        self.medians={}; self.mads={}
        self.feature_cols=[]; self.fitted=False

    def fit(self,normal_df,feature_cols):
        self.feature_cols=[c for c in feature_cols if c in normal_df.columns]
        for col in self.feature_cols:
            v=normal_df[col].dropna().values
            self.medians[col]=float(np.median(v))
            self.mads[col]=float(median_abs_deviation(v)+1e-6)
        self.fitted=True
        print(f"    Statistical: {len(self.feature_cols)} features")

    def score_row(self,features):
        z_scores={}
        for col in self.feature_cols:
            val=features.get(col,self.medians.get(col,0))
            mz=0.6745*abs(val-self.medians.get(col,0))/self.mads.get(col,1)
            z_scores[col]=float(mz)
        if not z_scores: return {'statistical_aggregate':0.0}
        p90_z=np.percentile(list(z_scores.values()),90)
        agg=float(np.clip((p90_z-3.0)/5.0,0,1))
        result={f'z_{c}':float(np.clip(z/8,0,1)) for c,z in z_scores.items()}
        result['statistical_aggregate']=agg
        return result

