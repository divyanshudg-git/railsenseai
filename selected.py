class FusionLayer:
    def __init__(self):
        self.weights={'physics':0.55,'temporal':0.15,'statistical':0.30}
        self.threshold=0.60; self.fitted=False

    def fit(self, p_tr,t_tr,s_tr,l_tr, p_vl,t_vl,s_vl,l_vl):
        n_fail_v=l_vl.sum(); n_norm_v=len(l_vl)-n_fail_v
        print(f"\n    Fusion optimization...")
        print(f"    Train (SMOTE): {len(l_tr):,} ({l_tr.sum():,} fail)")
        print(f"    Val (original): {len(l_vl):,} ({n_fail_v:,} fail)")

        # Check if temporal engine is actually contributing
        print(f"\n    Engine separation check (Val):")
        print(f"      Physics   : {abs(p_vl[l_vl==1].mean()-p_vl[l_vl==0].mean()):.4f}")
        print(f"      Temporal  : {abs(t_vl[l_vl==1].mean()-t_vl[l_vl==0].mean()):.4f}")
        print(f"      Statistical:{abs(s_vl[l_vl==1].mean()-s_vl[l_vl==0].mean()):.4f}")

        def objective(params):
            w=np.abs(params[:3]); w=w/(w.sum()+1e-10)
            t=float(np.clip(params[3],0.20,0.85))

            # Score SMOTE train set for optimization
            scores_tr=np.clip(w[0]*p_tr+w[1]*t_tr+w[2]*s_tr,0,1)
            preds_tr=(scores_tr>=t).astype(int)

            # Score val set for generalization check
            scores_vl=np.clip(w[0]*p_vl+w[1]*t_vl+w[2]*s_vl,0,1)
            preds_vl=(scores_vl>=t).astype(int)

            tp_v=((preds_vl==1)&(l_vl==1)).sum()
            fp_v=((preds_vl==1)&(l_vl==0)).sum()
            fn_v=((preds_vl==0)&(l_vl==1)).sum()
            tn_v=((preds_vl==0)&(l_vl==0)).sum()

            rec_v =tp_v/(tp_v+fn_v+1e-10)
            prec_v=tp_v/(tp_v+fp_v+1e-10)
            f1_v  =2*rec_v*prec_v/(rec_v+prec_v+1e-10)

            # Cost matrix: FN=15 (safety), FP=1
            cost = ((fn_v*15) + (fp_v*1)) / len(l_vl)

            # Hard constraints
            recall_floor = max(0, 0.85-rec_v)  * 20.0
            prec_floor   = max(0, 0.88-prec_v) * 10.0

            return -(f1_v - cost - recall_floor - prec_floor)

        result=differential_evolution(
            objective,
            bounds=[(0.2,0.9),(0.0,0.3),(0.1,0.7),(0.25,0.80)],
            seed=42, maxiter=2000, popsize=30,
            tol=1e-7, mutation=(0.4,1.2),
            recombination=0.9, polish=True, init='sobol',
        )

        params=result.x
        w=np.abs(params[:3]); w=w/w.sum()
        self.weights={'physics':float(w[0]),'temporal':float(w[1]),'statistical':float(w[2])}
        self.threshold=float(np.clip(params[3],0.20,0.85))
        self.fitted=True

        print(f"\n    Weights: P={self.weights['physics']:.3f}  "
              f"T={self.weights['temporal']:.3f}  "
              f"S={self.weights['statistical']:.3f}")
        print(f"    Threshold: {self.threshold:.4f}")

        for name,ps,ts,ss,ls in [
            ('Train(SMOTE)',p_tr,t_tr,s_tr,l_tr),
            ('Val        ',p_vl,t_vl,s_vl,l_vl)
        ]:
            fs=np.clip(w[0]*ps+w[1]*ts+w[2]*ss,0,1)
            fp_=(fs>=self.threshold).astype(int)
            print(f"    {name}: Rec={recall_score(ls,fp_,zero_division=0):.4f}  "
                  f"Prec={precision_score(ls,fp_,zero_division=0):.4f}  "
                  f"F1={f1_score(ls,fp_,zero_division=0):.4f}")

    def fuse(self,p,t,s):
        w=self.weights
        score=float(np.clip(w['physics']*p+w['temporal']*t+w['statistical']*s,0,1))
        conf=float(np.clip(abs(score-self.threshold)/0.3,0,1))
        if score>=self.threshold*1.25: level='CRITICAL'
        elif score>=self.threshold:    level='WARNING'
        else:                          level='NORMAL'
        return score,level,conf

