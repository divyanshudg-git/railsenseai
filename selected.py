# ============================================================
# PTAD v2.4 — Imbalance-First Architecture
# Strategy: BorderlineSMOTE on physics features → better failure
#            learning → higher recall without sacrificing precision
#
# Why BorderlineSMOTE not regular SMOTE:
#   Regular SMOTE: generates points anywhere in failure space
#   BorderlineSMOTE: only generates points NEAR decision boundary
#   → More realistic synthetic failures
#   → Model learns hard cases, not easy ones
#
# Why feature-space SMOTE not raw-sensor SMOTE:
#   Raw sensors are correlated + temporal → SMOTE breaks physics
#   Feature space (pressure_diff, duty_cycle etc) = engineered signals
#   → SMOTE interpolation in feature space is physically meaningful
# ============================================================

