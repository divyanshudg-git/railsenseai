class PhysicsEngine:
    def __init__(self):
        self.thresholds={
            'duty_warn':0.92,'duty_crit':0.99,
            'temp_warn':72.0,'temp_crit':78.0,
            'motor_warn':5.50,'motor_crit':5.90,
            'variance_low_warn':2.0,'variance_low_crit':0.8,
            'pdiff_warn':0.015,'pdiff_crit':0.025,
            'divergence_warn':2.0,'divergence_crit':4.0,
        }

    def _sigmoid(self,v,warn,crit,invert=False):
        if invert: v,warn,crit=-v,-warn,-crit
        if v<=warn: return 0.0
        if v>=crit: return 1.0
        t=(v-warn)/(crit-warn+1e-10)
        return float(3*t**2-2*t**3)

    def evaluate(self,f):
        duty=f.get('duty_cycle_5min',0)
        temp=f.get('Oil_temperature',60)
        motor=f.get('Motor_current',0)
        var=f.get('pressure_variance_10min',5)
        eff=f.get('compressor_efficiency',100)
        p_diff=abs(f.get('pressure_diff',0))
        div=f.get('sensor_divergence',0.5)
        mismatch=f.get('comp_mpg_disagreement',0)
        motor_on=motor>4.0
        compound=(eff<3.0)and(duty>0.90)and(motor>5.0)
        return [
            PhysicsSignal('P1_duty',self._sigmoid(duty,0.92,0.99),duty,0.92,f'Duty={duty:.3f}','COMPRESSOR_OVERLOAD'),
            PhysicsSignal('P2_temp',self._sigmoid(temp,72,78),temp,72,f'Oil={temp:.1f}C','THERMAL_DEGRADATION'),
            PhysicsSignal('P3_motor',self._sigmoid(motor,5.5,5.9),motor,5.5,f'Motor={motor:.2f}A','COMPRESSOR_OVERLOAD'),
            PhysicsSignal('P4_var',self._sigmoid(var,2.0,0.8,invert=True) if motor_on else 0.0,var,2.0,f'Var={var:.4f}','AIR_LEAK_PRESSURE'),
            PhysicsSignal('P5_compound',1.0 if compound else 0.0,eff,3.0,f'Compound:eff={eff:.2f}','EFFICIENCY_COLLAPSE'),
            PhysicsSignal('P6_pdiff',self._sigmoid(p_diff,0.015,0.025),p_diff,0.015,f'pdiff={p_diff:.4f}','AIR_LEAK_PRESSURE'),
            PhysicsSignal('P7_div',self._sigmoid(div,2.0,4.0),div,2.0,f'div={div:.3f}','AIR_LEAK_INSTAB'),
            PhysicsSignal('P8_valve',float(mismatch),mismatch,0.5,'COMP/MPG','VALVE_FAULT'),
        ]

    def aggregate(self,signals):
        s=np.array([sig.score for sig in signals])
        w=np.array([0.30,0.20,0.18,0.12,0.10,0.02,0.04,0.04])
        weighted=float(np.dot(s,w))
        pf=sum([s[0]>0.3,s[1]>0.3,s[2]>0.3])
        if pf==3: weighted=min(1.0,weighted*1.5)
        elif pf==2: weighted=min(1.0,weighted*1.2)
        return float(np.clip(weighted,0,1))

